// Copies the Supabase migrations into a TypeScript module so the browser demo can run the exact same
// database code as production. Runs automatically before dev, build and test.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const dir = path.resolve(here, "../../supabase/migrations");
const files = fs.readdirSync(dir).filter((f) => f.endsWith(".sql")).sort();
const body = files.map((f) => `  ${JSON.stringify(fs.readFileSync(path.join(dir, f), "utf8"))},`).join("\n");
const out = `// GENERATED by scripts/sync-migrations.mjs from supabase/migrations. Do not edit.\nexport const MIGRATIONS: string[] = [\n${body}\n];\n`;
const target = path.resolve(here, "../src/lib/demo/migrations.generated.ts");
fs.writeFileSync(target, out);
console.log(`Synced ${files.length} migrations -> ${path.relative(process.cwd(), target)}`);
